            function parseCSV(text) {
                const rows = [];
                const lines = text.trim().split('\n');
                const re = /^("([^"]+)"|([^,]+)),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+)/;
                lines.forEach(line => {
                    const m = line.match(re);
                    if (!m) return;
                    const name = m[2] || m[3];
                    rows.push({
                        name: name.trim(),
                        cal155: parseInt(m[5], 10),  // 155 lb column
                    });
                });
                return rows;
            }

